/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_FDCAN1_Init();
  /* USER CODE BEGIN 2 */
  FDCAN_FilterTypeDef filter = {0};

  // Accept ALL standard CAN IDs
  filter.IdType = FDCAN_STANDARD_ID;
  filter.FilterIndex = 0;
  filter.FilterType = FDCAN_FILTER_MASK;
  filter.FilterConfig = FDCAN_FILTER_TO_RXFIFO0;
  filter.FilterID1 = 0x000;
  filter.FilterID2 = 0x000;

  if (HAL_FDCAN_ConfigFilter(&hfdcan1, &filter) != HAL_OK)
  {
      Error_Handler();
  }

  // Reject other unmatched frames and remote frames
  if (HAL_FDCAN_ConfigGlobalFilter(
          &hfdcan1,
          FDCAN_ACCEPT_IN_RX_FIFO0,
          FDCAN_ACCEPT_IN_RX_FIFO0,
          FDCAN_REJECT_REMOTE,
          FDCAN_REJECT_REMOTE) != HAL_OK)
  {
      Error_Handler();
  }

  // Start receiving
  if (HAL_FDCAN_Start(&hfdcan1) != HAL_OK)
  {
      Error_Handler();
  }
  /* USER CODE END 2 */

  /* Initialize led */
  BSP_LED_Init(LED_GREEN);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Initialize COM1 port (115200, 8 bits (7-bit data + 1 stop bit), no parity */
  BspCOMInit.BaudRate   = 115200;
  BspCOMInit.WordLength = COM_WORDLENGTH_8B;
  BspCOMInit.StopBits   = COM_STOPBITS_1;
  BspCOMInit.Parity     = COM_PARITY_NONE;
  BspCOMInit.HwFlowCtl  = COM_HWCONTROL_NONE;
  if (BSP_COM_Init(COM1, &BspCOMInit) != BSP_ERROR_NONE)
  {
    Error_Handler();
  }

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  char buf[128];

  uart_print("GPS CAN receiver ready\r\n");

  while (1)
  {

    // Check whether a CAN message arrived
    if (HAL_FDCAN_GetRxFifoFillLevel(
            &hfdcan1, FDCAN_RX_FIFO0) > 0)
    {
        if (HAL_FDCAN_GetRxMessage(
                &hfdcan1,
                FDCAN_RX_FIFO0,
                &RxHeader,
                RxData) == HAL_OK)
        {
            // Print CAN ID
            snprintf(buf, sizeof(buf),
                     "CAN ID: 0x%03lX | Data: ",
                     (unsigned long)RxHeader.Identifier);

            uart_print(buf);

            // Print the valid data bytes (handles both DLC encodings)
            uint32_t dl = RxHeader.DataLength;
            uint8_t len = (dl > 8) ? (uint8_t)(dl >> 16) : (uint8_t)dl;
            if (len > 8) len = 8;

            for (int i = 0; i < len; i++)
            {
                snprintf(buf, sizeof(buf), "%02X ", RxData[i]);
                uart_print(buf);
            }

            uart_print("\r\n");
        }
    }

    static uint32_t last = 0;
    if (HAL_GetTick() - last >= 1000)
    {
        last = HAL_GetTick();
        FDCAN_ProtocolStatusTypeDef ps;
        FDCAN_ErrorCountersTypeDef ec;
        HAL_FDCAN_GetProtocolStatus(&hfdcan1, &ps);
        HAL_FDCAN_GetErrorCounters(&hfdcan1, &ec);
        snprintf(buf, sizeof(buf),
                "LEC=%lu ACT=0x%lX BO=%lu EP=%lu TEC=%lu REC=%lu\r\n",
                (unsigned long)ps.LastErrorCode, (unsigned long)ps.Activity,
                (unsigned long)ps.BusOff, (unsigned long)ps.ErrorPassive,
                (unsigned long)ec.TxErrorCnt, (unsigned long)ec.RxErrorCnt);
        uart_print(buf);
    }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

