/**
  * @brief FDCAN RX FIFO 0 callback
  * @param hfdcan FDCAN handle
  * @param RxFifo0ITs Interrupt flags
  */
void HAL_FDCAN_RxFifo0Callback(FDCAN_HandleTypeDef *hfdcan,
                                uint32_t RxFifo0ITs)
{
  if (hfdcan->Instance == FDCAN2)
  {
    if ((RxFifo0ITs & FDCAN_IT_RX_FIFO0_NEW_MESSAGE) != 0)
    {
      /* Read the message from RX FIFO 0 */
      if (HAL_FDCAN_GetRxMessage(hfdcan,
                                 FDCAN_RX_FIFO0,
                                 &RxHeader,
                                 RxData) == HAL_OK)
      {
        /*
         * Check for exactly 8 data bytes:
         * 0, 1, 2, 3, 4, 5, 6, 7
         */
        if ((RxHeader.DataLength == FDCAN_DLC_BYTES_8) &&
            (RxData[0] == 0) &&
            (RxData[1] == 1) &&
            (RxData[2] == 2) &&
            (RxData[3] == 3) &&
            (RxData[4] == 4) &&
            (RxData[5] == 5) &&
            (RxData[6] == 6) &&
            (RxData[7] == 7))
        {
          /*
           * Matching CAN message received.
           *
           * Turn on PA9 as an example response.
           */
          HAL_GPIO_WritePin(GPIOA, GPIO_PIN_9, GPIO_PIN_SET);
        }
      }
    }
  }
}
